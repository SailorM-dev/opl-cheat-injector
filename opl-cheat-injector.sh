# ------------------------------------------------------------
# Locate an OPL device safely
# ------------------------------------------------------------

is_opl_root() {
    local path="$1"

    [[ -d "$path" ]] || return 1
    [[ -d "$path/DVD" || -d "$path/CD" || -d "$path/CHT" ]]
}

canonical_directory() {
    local path="$1"

    (cd -- "$path" 2>/dev/null && pwd -P)
}

declare -a OPL_CANDIDATES=()
declare -A SEEN_CANDIDATES=()

add_candidate() {
    local path="$1"
    local canonical

    is_opl_root "$path" || return 0
    canonical="$(canonical_directory "$path" || true)"
    [[ -n "$canonical" ]] || return 0

    if [[ -z "${SEEN_CANDIDATES[$canonical]+x}" ]]; then
        OPL_CANDIDATES+=("$canonical")
        SEEN_CANDIDATES["$canonical"]=1
    fi
}

select_opl_root() {
    local script_directory
    local selected
    local reply
    local path
    local index

    if [[ -n "$REQUESTED_ROOT" ]]; then
        if ! is_opl_root "$REQUESTED_ROOT"; then
            echo "ERROR: This does not look like an OPL device root:" >&2
            echo "  $REQUESTED_ROOT" >&2
            echo "Expected at least one of these directories: DVD, CD, CHT" >&2
            exit 1
        fi

        canonical_directory "$REQUESTED_ROOT"
        return
    fi

    script_directory="$(
        cd -- "$(dirname -- "${BASH_SOURCE[0]}")" 2>/dev/null && pwd -P
    )"

    add_candidate "$script_directory"
    add_candidate "$PWD"

    shopt -s nullglob
    for path in \
        /media/*/* \
        /run/media/*/* \
        /mnt/* \
        /Volumes/*; do
        add_candidate "$path"
    done
    shopt -u nullglob

    if (( ${#OPL_CANDIDATES[@]} == 1 )); then
        printf '%s\n' "${OPL_CANDIDATES[0]}"
        return
    fi

    if (( ${#OPL_CANDIDATES[@]} > 1 )); then
        if [[ ! -t 0 ]]; then
            echo "ERROR: Multiple OPL devices found; use --root PATH." >&2
            for path in "${OPL_CANDIDATES[@]}"; do
                echo "  $path" >&2
            done
            exit 1
        fi

        echo "Multiple OPL devices found:" >&2
        echo >&2
        for index in "${!OPL_CANDIDATES[@]}"; do
            printf '%d) %s\n' "$((index + 1))" "${OPL_CANDIDATES[index]}" >&2
        done
        echo >&2

        while true; do
            read -r -p "Select device [1-${#OPL_CANDIDATES[@]}]: " reply
            if [[ "$reply" =~ ^[0-9]+$ ]] &&
                (( reply >= 1 && reply <= ${#OPL_CANDIDATES[@]} )); then
                selected="${OPL_CANDIDATES[reply - 1]}"
                printf '%s\n' "$selected"
                return
            fi
            echo "Please enter a number from 1 to ${#OPL_CANDIDATES[@]}." >&2
        done
    fi

    if [[ ! -t 0 ]]; then
        echo "ERROR: No OPL device detected; use --root PATH." >&2
        exit 1
    fi

    echo "No OPL device was detected automatically." >&2
    while true; do
        read -r -p "Enter the OPL device root path: " reply

        if is_opl_root "$reply"; then
            canonical_directory "$reply"
            return
        fi

        echo "That path does not contain a DVD, CD, or CHT directory." >&2
    done
}

OPL_ROOT="$(select_opl_root)"
DVD="$OPL_ROOT/DVD"
