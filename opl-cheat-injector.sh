REQUESTED_ROOT=""

usage() {
    cat <<'EOF'
Usage:
  ./opl-cheat-injector.sh
  ./opl-cheat-injector.sh --root /path/to/OPL/device
  ./opl-cheat-injector.sh /path/to/OPL/device

