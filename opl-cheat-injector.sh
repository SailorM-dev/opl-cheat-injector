# ------------------------------------------------------------
# Extract and normalize a PS2 serial from arbitrary text.
#
# Supports:
# SLUS_211.34
# SLUS-21134
# SLUS_21134
# SLES_537.02
# ------------------------------------------------------------

extract_serial() {
    local text="$1"

    printf '%s\n' "$text" |
        grep -Eiom1 "$SERIAL_REGEX" |
        tr '[:lower:]' '[:upper:]'
}

# ------------------------------------------------------------
# Read a serial from a game's filename or ISO contents.
#
# OPL-style filenames are checked first. For an ISO without a
# serial in its filename, scan the first 64 MiB; SYSTEM.CNF and
# its BOOT2 executable entry are normally near the beginning.
#
# ZSO contents are compressed, so ZSO games must currently have
# an OPL serial in their filename.
# ------------------------------------------------------------

get_game_serial() {
    local game="$1"
    local filename
    local serial

    filename="$(basename "$game")"
    serial="$(extract_serial "$filename" || true)"

    if [[ -n "$serial" ]]; then
        printf '%s\n' "$serial"
        return 0
    fi

    if [[ "${game,,}" == *.iso ]]; then
        serial="$(
            dd if="$game" bs=1M count=64 status=none 2>/dev/null |
                strings -n 8 |
                grep -Eiom1 "$SERIAL_REGEX" |
                tr '[:lower:]' '[:upper:]' || true
        )"

        if [[ -n "$serial" ]]; then
            printf '%s\n' "$serial"
            return 0
        fi
    fi

    return 1
}

# ------------------------------------------------------------
# Normalize into OPL filename format:
#
# SLUS-21134  -> SLUS_211.34
# SLUS_21134  -> SLUS_211.34
# SLUS_211.34 -> SLUS_211.34
# ------------------------------------------------------------

normalize_opl_serial() {
    local s="$1"

    s="${s//-/_}"
    s="${s//./}"

    if [[ "$s" =~ ^([A-Z]{4})_([0-9]{3})([0-9]{2})$ ]]; then
        echo "${BASH_REMATCH[1]}_${BASH_REMATCH[2]}.${BASH_REMATCH[3]}"
        return
    fi

    echo "$s"
}

# ------------------------------------------------------------
# Find exact trusted CHT match
# ------------------------------------------------------------

find_trusted_cht() {
    local serial="$1"

    find "$TRUSTED_REPO" \
        -type f \
        -iname "${serial}.cht" \
        -print \
        -quit
}

# ------------------------------------------------------------
# Validate native OPL CHT
#
# v0.1a requirements:
# - file exists
# - contains raw 8+8 hex code lines
# - contains at least one code beginning with 9
#
# This does NOT prove the cheat itself is correct.
# It only validates expected native PS2RD structure.
# ------------------------------------------------------------

validate_cht() {
    local file="$1"
    local raw_count
    local master_count

    [[ -f "$file" ]] || return 1

    raw_count="$(
        grep -Ec \
            '^[[:space:]]*[0-9A-Fa-f]{8}[[:space:]]+[0-9A-Fa-f]{8}[[:space:]]*$' \
            "$file" || true
    )"

    master_count="$(
        grep -Ec \
            '^[[:space:]]*9[0-9A-Fa-f]{7}[[:space:]]+[0-9A-Fa-f]{8}[[:space:]]*$' \
            "$file" || true
    )"

    (( raw_count > 0 && master_count > 0 ))
}

# ------------------------------------------------------------
# Determine whether an existing file was generated by any
# version of this script, while preserving truly manual files.
# ------------------------------------------------------------

is_managed_file() {
    local file="$1"

    [[ -f "$file" ]] || return 1
    grep -qF "$MANAGED_PREFIX" "$file"
}

# ------------------------------------------------------------
# Install trusted file
# ------------------------------------------------------------

install_trusted_cht() {
    local source="$1"
    local dest="$2"
    local serial="$3"

    {
        echo "$MANAGED_TAG"
        echo "# Serial: $serial"
        echo "# Source: $TRUSTED_REPO_URL"
        echo "# Classification: TRUSTED NATIVE CHT SOURCE"
        echo
        cat "$source"
    } > "$dest.tmp"

    mv "$dest.tmp" "$dest"
}

# ------------------------------------------------------------
# Build game list
# ------------------------------------------------------------

mapfile -t GAMES < <(
    find "$DVD" "$CD" \
        -maxdepth 1 \

        -type f \
        \( -iname '*.iso' -o -iname '*.zso' \) \
        2>/dev/null |
        sort
)

if (( ${#GAMES[@]} == 0 )); then
    echo "No PS2 ISO/ZSO games found."
    echo
    echo "Checked:"
    echo "  $DVD"
    echo "  $CD"
    exit 0
fi

# ------------------------------------------------------------
# Counters
# ------------------------------------------------------------

scanned=0
identified=0
trusted=0
installed=0
manual_spared=0
invalid=0
nomatch=0
noserial=0

echo "Scanning MX4SIO library..."

# ------------------------------------------------------------
# Main scan
# ------------------------------------------------------------

for game in "${GAMES[@]}"; do
    ((scanned+=1)) || true

    filename="$(basename "$game")"
    raw_serial="$(get_game_serial "$game" || true)"

    if [[ -z "$raw_serial" ]]; then
        echo
        echo "[NO SERIAL] $filename"
        if [[ "${game,,}" == *.zso ]]; then
            echo "  - ZSO content is compressed; put its serial in the filename"
        fi
        ((noserial+=1)) || true
        continue
    fi

    serial="$(normalize_opl_serial "$raw_serial")"
    ((identified+=1)) || true

    echo
    echo "[$serial] $filename"

    source_cht="$(find_trusted_cht "$serial" || true)"

    if [[ -z "$source_cht" ]]; then
        echo "  - No trusted native CHT match"
        ((nomatch+=1)) || true
        continue
    fi

    ((trusted+=1)) || true

    if ! validate_cht "$source_cht"; then
        echo "  ! Native CHT found, but validation failed"
        echo "  -> QUARANTINED"
        cp -f "$source_cht" "$QUARANTINE/$serial.cht"
        ((invalid+=1)) || true
        continue
    fi

    outfile="$CHT/$serial.cht"

    if [[ -f "$outfile" ]] && ! is_managed_file "$outfile"; then
        echo "  ! Existing manual CHT preserved"
        ((manual_spared+=1)) || true
        continue
    fi

    install_trusted_cht \
        "$source_cht" \
        "$outfile" \
        "$serial"

    echo "  + Exact serial match"
    echo "  + Native PS2RD CHT"
    echo "  + 9-type mastercode present"
    echo "  -> INJECTED"

    ((installed+=1)) || true
done

